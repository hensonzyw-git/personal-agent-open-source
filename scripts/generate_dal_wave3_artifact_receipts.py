#!/usr/bin/env python3
"""Generate per-variant Wave 3 machine-artifact rebuild receipts.

Wave 3 §9 item 1 (frozen contract package `docs/dal/DAL021-024_合同冻结包_v0.1.md`
§9) requires the frozen oracle/authority artifacts and the test-manifest
extension rows to be regenerated by ``build_contract_manifests.py`` and bound
per variant. The manifest v1.2 freeze already reserved the rows and the
generator already emits them, so what was still missing is the per-variant
proof that a fresh deterministic rebuild reproduces the frozen bytes and that
every authority covers them.

This generator produces one ``dal.artifact-rebuild-receipt/1.0`` per Wave 3
variant (14 variants: PROVIDER-CONTRACT x8, REVIEW-INDEP x5, INJECTION
provider_output) under ``docs/evidence/artifact-receipts/``. Each receipt
records the recomputed fixture/oracle content hashes, the manifest row digest,
the authority coverage of that variant, the zero-drift rebuild evidence, and
the generator commit the rebuild ran against.

It is deliberately NOT a ``dal.test-receipt/1.0``: that schema means
"implementation executed and passed against the frozen oracle" (§9 item 3).
Binding the artifact stage to that semantics would silently claim G3/G4
implementation, which has not happened and is not authorised.

Fail-closed: the generator refuses to write anything unless the rebuild is
byte-identical (git snapshot compare), all four authorities verify, and every
receipt's recomputed hashes match the manifest row. No truncation, no repair.
"""

