#!/usr/bin/env python3
"""Verify the eval-run manifest schema against a static external authority."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path

from dal_jcs import canonical_bytes


ROOT = Path(__file__).resolve().parent
DEFAULT_SCHEMA = ROOT / "manifests" / "eval-run-manifest_schema_v1.0.json"
DEFAULT_AUTHORITY = ROOT / "manifests" / "eval-schema-authority_v1.0.json"
AUTHORITY_KEYS = {
    "schema_version", "authority_version", "source_boundary",
    "frozen_file_sha256", "expected_semantics", "authority_sha256",
}


class AuthorityVerificationError(ValueError):
    """The generated eval schema differs from the frozen authority."""


def digest(value: object) -> str:
    return hashlib.sha256(canonical_bytes(value)).hexdigest()


def load_json(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise AuthorityVerificationError(f"expected JSON object: {path}")
    return value


def hashed_payload(value: dict, hash_field: str) -> dict:
    payload = copy.deepcopy(value)
    payload.pop(hash_field, None)
    return payload


def generated_bytes(schema: dict) -> bytes:
    return (json.dumps(schema, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")


def expected_semantics(schema: dict) -> dict[str, object]:
    case_items = schema["properties"]["case_inputs"]["items"]
    route = schema["properties"]["route"]
    limits = schema["properties"]["limits"]
    profiles = schema["allOf"][0]["oneOf"]
    ready = schema["allOf"][1]
    ready_route = ready["then"]["properties"]["route"]["properties"]
    ready_limits = ready["then"]["properties"]["limits"]["properties"]
    return {
        "root_fields": sorted(schema),
        "root_required": schema["required"],
        "root_additional_properties": schema["additionalProperties"],
        "run_input_required": case_items["required"],
        "run_input_additional_properties": case_items["additionalProperties"],
        "route_required": route["required"],
        "route_additional_properties": route["additionalProperties"],
        "limits_required": limits["required"],
        "limits_additional_properties": limits["additionalProperties"],
        "profile_case_order": {
            branch["properties"]["series_profile"]["const"]:
                branch["properties"]["case_ids_and_order"]["const"]
            for branch in profiles
        },
        "ready_statuses": ready["if"]["properties"]["series_status"]["enum"],
        "ready_route_non_null_fields": sorted(ready_route),
        "ready_limit_fields": sorted(ready_limits),
        "ready_max_fix_review_cycles": ready_limits["max_fix_review_cycles"]["const"],
        "repeat_n": schema["properties"]["repeat_n"]["const"],
        "series_profiles": schema["properties"]["series_profile"]["enum"],
        "series_statuses": schema["properties"]["series_status"]["enum"],
        "canonicalization": schema["x-canonicalization"],
    }


def _verify_loaded(authority: dict, schema: dict, schema_bytes: bytes) -> dict[str, int]:
    if set(authority) != AUTHORITY_KEYS:
        raise AuthorityVerificationError("eval authority root fields are not closed")
    if authority["schema_version"] != "dal.eval-schema-authority/1.0":
        raise AuthorityVerificationError("eval authority schema version mismatch")
    if authority["authority_version"] != "1.0":
        raise AuthorityVerificationError("eval authority version mismatch")
    if authority["source_boundary"] != "static-independent-review-authority; never generated by build_contract_manifests.py":
        raise AuthorityVerificationError("eval authority source boundary mismatch")
    if digest(hashed_payload(authority, "authority_sha256")) != authority["authority_sha256"]:
        raise AuthorityVerificationError("eval authority self-hash mismatch")
    if hashlib.sha256(schema_bytes).hexdigest() != authority["frozen_file_sha256"]:
        raise AuthorityVerificationError("eval schema bytes differ from independent authority")
    semantics = expected_semantics(schema)
    if semantics != authority["expected_semantics"]:
        raise AuthorityVerificationError("eval schema semantics differ from independent authority")
    return {
        "root_fields": len(semantics["root_fields"]),
        "root_required": len(semantics["root_required"]),
        "run_input_required": len(semantics["run_input_required"]),
        "p4_cases": len(semantics["profile_case_order"]["P4"]),
        "p5_cases": len(semantics["profile_case_order"]["P5"]),
    }


def verify_authority(schema_path: Path = DEFAULT_SCHEMA, authority_path: Path = DEFAULT_AUTHORITY) -> dict[str, int]:
    return _verify_loaded(load_json(authority_path), load_json(schema_path), schema_path.read_bytes())


def mutation_self_test(schema_path: Path = DEFAULT_SCHEMA, authority_path: Path = DEFAULT_AUTHORITY) -> list[str]:
    authority = load_json(authority_path)
    source = load_json(schema_path)

    def remove_tool_policy(schema: dict) -> None:
        schema["properties"]["case_inputs"]["items"]["required"].remove("tool_policy_sha256")

    def add_root_field(schema: dict) -> None:
        schema["x-unapproved"] = True

    def remove_route_binding(schema: dict) -> None:
        schema["properties"]["route"]["required"].remove("classifier_sha256")

    def reorder_p5(schema: dict) -> None:
        schema["allOf"][0]["oneOf"][1]["properties"]["case_ids_and_order"]["const"].reverse()

    def weaken_ready_limit(schema: dict) -> None:
        schema["allOf"][1]["then"]["properties"]["limits"]["properties"]["max_fix_review_cycles"] = {"minimum": 0}

    def change_canonicalization(schema: dict) -> None:
        schema["x-canonicalization"]["algorithm"] = "implementation-defined"

    mutations = (
        ("tool_policy_required", remove_tool_policy),
        ("root_extra", add_root_field),
        ("route_binding", remove_route_binding),
        ("p5_order", reorder_p5),
        ("ready_limit", weaken_ready_limit),
        ("canonicalization", change_canonicalization),
    )
    passed: list[str] = []
    for label, mutate in mutations:
        schema = copy.deepcopy(source)
        mutate(schema)
        try:
            _verify_loaded(authority, schema, generated_bytes(schema))
        except AuthorityVerificationError:
            passed.append(label)
        else:
            raise AuthorityVerificationError(f"{label} eval schema mutation escaped authority")
    return passed


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--authority", type=Path, default=DEFAULT_AUTHORITY)
    parser.add_argument("--mutation-self-test", action="store_true")
    args = parser.parse_args()
    counts = verify_authority(args.schema, args.authority)
    mutations = mutation_self_test(args.schema, args.authority) if args.mutation_self_test else []
    print(json.dumps({"authority": "PASS", "counts": counts, "mutations_rejected": mutations}, sort_keys=True))


if __name__ == "__main__":
    main()
